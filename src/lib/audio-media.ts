// Pure helpers for the admin Media (shareable audio) module. No server-only or `@/` imports so
// tests/unit.test.mjs can load this file directly.

/** Chunk size the admin uploader sends. Small enough for Cloudflare (100MB/request) and ModSecurity. */
export const AUDIO_CHUNK_BYTES = 4 * 1024 * 1024

/** Largest single audio file accepted. */
export const AUDIO_MAX_BYTES = 1024 * 1024 * 1024

/** Extension → Content-Type for every audio format we accept and serve. */
export const AUDIO_TYPES: Record<string, string> = {
  '.mp3': 'audio/mpeg',
  // MPEG audio under other names (.mpeg/.mpg files from recorders and converters are usually MPEG audio).
  '.mpeg': 'audio/mpeg',
  '.mpg': 'audio/mpeg',
  '.mpga': 'audio/mpeg',
  '.mpa': 'audio/mpeg',
  '.mp2': 'audio/mpeg',
  '.m2a': 'audio/mpeg',
  '.m4a': 'audio/mp4',
  '.m4b': 'audio/mp4',
  '.mp4': 'audio/mp4',
  '.aac': 'audio/aac',
  '.wav': 'audio/wav',
  '.ogg': 'audio/ogg',
  '.oga': 'audio/ogg',
  '.opus': 'audio/ogg',
  '.flac': 'audio/flac',
  '.webm': 'audio/webm',
  '.weba': 'audio/webm',
  '.aif': 'audio/aiff',
  '.aiff': 'audio/aiff',
  '.amr': 'audio/amr',
  '.wma': 'audio/x-ms-wma',
  '.caf': 'audio/x-caf',
  '.3gp': 'audio/3gpp',
}

/**
 * Formats some browsers cannot play inline; the listen page adds a "download it" hint. .mpeg/.mpg can also be
 * MPEG video, which an audio player can't decode.
 */
export const AUDIO_NOT_BROWSER_PLAYABLE = new Set(['.aif', '.aiff', '.amr', '.wma', '.caf', '.3gp', '.mpeg', '.mpg'])

/** Lower-case extension of a filename, including the dot, or '' if none. */
export function audioExtension(fileName: string): string {
  const m = /\.[a-z0-9]{1,5}$/i.exec(fileName.trim())
  return m ? m[0].toLowerCase() : ''
}

/** True when the file name has an extension we accept as audio. */
export function isAcceptedAudio(fileName: string): boolean {
  return audioExtension(fileName) in AUDIO_TYPES
}

/** URL-safe slug from a title, with a random suffix so links can't be guessed or collide. */
export function audioSlug(title: string, suffix: string): string {
  const base = title
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/g, '')
  return base ? `${base}-${suffix}` : suffix
}

/** Title from a filename: drops the extension and turns _ / - into spaces. */
export function titleFromFileName(fileName: string): string {
  return fileName
    .replace(/\.[^.]+$/, '')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/** Upload session ids are generated by the browser; keep them to a safe filename alphabet. */
export function isValidUploadId(id: string): boolean {
  return /^[a-z0-9]{16,40}$/.test(id)
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(0)} KB`
  if (bytes < 1024 * 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
  return `${(bytes / (1024 * 1024 * 1024)).toFixed(2)} GB`
}
